// Helper functions for filtering - unchanged
export function searchNews(query: string, category?: string) {
    let results = newsArticles;

    if (query) {
        results = results.filter(article =>
            article.title.toLowerCase().includes(query.toLowerCase()) ||
            article.excerpt.toLowerCase().includes(query.toLowerCase())
        );
    }

    if (category && category !== "all") {
        results = results.filter(article => article.category === category);
    }

    return results;
}

export function searchAlbums(query: string, event?: string) {
    let results = photoAlbums;

    if (query) {
        results = results.filter(album =>
            album.title.toLowerCase().includes(query.toLowerCase()) ||
            album.artist.toLowerCase().includes(query.toLowerCase()) ||
            album.event.toLowerCase().includes(query.toLowerCase())
        );
    }

    if (event && event !== "all") {
        results = results.filter(album => album.event === event);
    }

    return results;
}

export function searchEvents(filters: {
    query?: string;
    type?: string;
    month?: string;
    province?: string;
    country?: string;
    upcoming?: boolean;
}) {
    let results = events;

    if (filters.query) {
        results = results.filter(event =>
            event.title.toLowerCase().includes(filters.query!.toLowerCase()) ||
            event.location.toLowerCase().includes(filters.query!.toLowerCase())
        );
    }

    if (filters.type && filters.type !== "all") {
        results = results.filter(event => event.type === filters.type);
    }

    if (filters.province && filters.province !== "all") {
        results = results.filter(event => event.province === filters.province);
    }

    if (filters.country && filters.country !== "all") {
        results = results.filter(event => event.country === filters.country);
    }
    // Simplified upcoming logic for demo since dates are in 2026

    return results;
}

export function searchArtists(query: string, genre?: string, letter?: string) {
    let results = artists;

    if (query) {
        results = results.filter(artist =>
            artist.name.toLowerCase().includes(query.toLowerCase())
        );
    }

    if (genre && genre !== "all") {
        results = results.filter(artist => artist.genre === genre);
    }

    if (letter && letter !== "all") {
        results = results.filter(artist =>
            artist.name.toUpperCase().startsWith(letter.toUpperCase())
        );
    }

    return results;
}

export function getMostPopularNews(limit = 5) {
    return [...newsArticles]
        .sort((a, b) => b.views - a.views)
        .slice(0, limit);
}

export function getUpcomingEvents(limit = 5) {
    return events.slice(0, limit);
}
